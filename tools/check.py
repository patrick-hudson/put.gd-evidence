#!/usr/bin/env python3
"""Validate evidence records.

  check.py record <dir> [--name NAME]    a candidate record directory on disk
  check.py push --base SHA --head SHA    a pushed commit range in this repository

Exit status: 0 valid, 1 one problem per line on stderr, 2 the check could not
run (bad arguments, unknown commit, not a git repository).

The publisher in put.gd-desktop (tools/maintenance/evidence.py) runs the record
command before it commits, and CI runs the push command. Both apply the same
rules. Standard library only, Python 3.10+.
"""
from __future__ import annotations

import argparse
import fnmatch
import os
import re
import stat
import subprocess
import sys
from collections import namedtuple

# The commit that imported docs/evidence from put.gd-desktop. Records present
# there predate the naming and README rules.
IMPORT_COMMIT = "874703b35562c732268c6fe0bc9b42614ffda928"
RECORDS = "records/"
INDEX = "records/README.md"  # generated by tools/index.py, exempt from add-only
AMEND_KEY = "Evidence-Amend"

NAME_RE = re.compile(r"^\d{4}-\d{2}-\d{2}-[a-z0-9][a-z0-9.-]*$")
MAX_FILE_BYTES = 50 * 1024 * 1024
# Without other files, a README needs this many non-space characters besides its
# title to say what was tested, where, and on which build.
MIN_README_CHARS = 80
FORBIDDEN_NAMES = (
    "credentials.txt",
    "creds.txt",
    ".env",
    "*.pem",
    "*.key",
    "id_rsa*",
    "id_ed25519*",
    "*.kdbx",
    ".netrc",
    "*.iso",
    "*.qcow2",
)

Entry = namedtuple("Entry", "path kind size")  # kind: file, dir, symlink, other


class GitError(Exception):
    pass


def decode_text(data):
    return data.decode("utf-8-sig", errors="replace")


def readme_title(text):
    """Return the text of the first `# ` heading outside a code fence, or None."""
    fence = None
    for line in text.splitlines():
        marker = re.match(r" {0,3}(`{3,}|~{3,})", line)
        if marker:
            if fence is None:
                fence = marker[1][0]
            elif marker[1][0] == fence:
                fence = None
        elif fence is None and line.startswith("# ") and line[2:].strip():
            return line[2:].strip()
    return None


def entry_problems(label, entry):
    where = f"{label}/{entry.path}"
    parts = entry.path.split("/")
    base = parts[-1].lower()
    problems = []
    if entry.kind == "symlink":
        problems.append(f"{where}: symlinks are not allowed")
    elif entry.kind == "other":
        problems.append(f"{where}: not a regular file")
    if ".git" in parts:
        problems.append(f"{where}: embedded git data is not allowed")
    if "__pycache__" in parts or (entry.kind != "dir" and base.endswith(".pyc")):
        problems.append(f"{where}: Python bytecode is not allowed")
    if entry.kind != "dir" and any(fnmatch.fnmatchcase(base, p) for p in FORBIDDEN_NAMES):
        problems.append(f"{where}: forbidden file name")
    if entry.size is not None and entry.size > MAX_FILE_BYTES:
        problems.append(f"{where}: {entry.size} bytes is over the 50 MiB limit")
    return problems


def name_problems(label, name):
    if NAME_RE.match(name):
        return []
    return [f"{label}: name must match YYYY-MM-DD-slug (lowercase letters, digits, dots, hyphens)"]


def readme_problems(label, entries, read_readme):
    files = [e for e in entries if e.kind != "dir"]
    readme = next((e for e in files if e.path == "README.md"), None)
    if readme is None:
        return [f"{label}: README.md is missing at the record's top level"]
    if readme.kind != "file":
        return [f"{label}: README.md is not a regular file"]
    try:
        text = read_readme()
    except OSError as error:
        return [f"{label}: README.md cannot be read: {error.strerror}"]
    title = readme_title(text)
    if title is None:
        return [f"{label}: README.md has no '# ' title line"]
    if len(files) == 1:
        body = sum(not c.isspace() for c in text) - sum(not c.isspace() for c in title) - 1
        if body < MIN_README_CHARS:
            return [f"{label}: no files besides README.md, and its body is under "
                    f"{MIN_README_CHARS} characters"]
    return []


def scan_directory(root):
    """List everything under root without following symlinks."""
    entries = []
    errors = []

    def fail(error):
        errors.append(f"{os.path.relpath(error.filename, root)}: {error.strerror}")

    for current, dirs, files in os.walk(root, onerror=fail):
        relative = os.path.relpath(current, root)
        prefix = "" if relative == "." else relative.replace(os.sep, "/") + "/"
        for name in list(dirs):
            full = os.path.join(current, name)
            if os.path.islink(full):
                entries.append(Entry(prefix + name, "symlink", None))
                dirs.remove(name)
            elif name in (".git", "__pycache__"):
                entries.append(Entry(prefix + name, "dir", None))
                dirs.remove(name)
        for name in files:
            info = os.lstat(os.path.join(current, name))
            if stat.S_ISLNK(info.st_mode):
                kind = "symlink"
            elif stat.S_ISREG(info.st_mode):
                kind = "file"
            else:
                kind = "other"
            entries.append(Entry(prefix + name, kind, info.st_size if kind == "file" else None))
    return entries, errors


def check_record(path, name):
    if name is None:
        name = os.path.basename(os.path.abspath(path))
    problems = name_problems(name, name)
    if os.path.islink(path):
        return problems + [f"{name}: the record directory is a symlink"]
    if not os.path.isdir(path):
        return problems + [f"{name}: {path} is not a directory"]
    entries, errors = scan_directory(path)
    problems += [f"{name}/{error}" for error in errors]
    for entry in entries:
        problems += entry_problems(name, entry)

    def read_readme():
        with open(os.path.join(path, "README.md"), "rb") as readme:
            return decode_text(readme.read())

    return problems + readme_problems(name, entries, read_readme)


def git(*args, stdin=None):
    try:
        result = subprocess.run(
            ["git", *args], input=stdin, stdout=subprocess.PIPE, stderr=subprocess.PIPE
        )
    except OSError as error:
        raise GitError(f"cannot run git: {error.strerror}") from error
    if result.returncode != 0:
        detail = result.stderr.decode(errors="replace").strip()
        raise GitError(f"git {args[0]} failed: {detail}")
    return result.stdout


def commit_id(rev, hint=""):
    try:
        return git("rev-parse", "--verify", "--quiet", f"{rev}^{{commit}}").decode().strip()
    except GitError as error:
        raise GitError(f"{rev} is not a commit in this repository{hint}") from error


def entry_kind(mode):
    if mode in ("100644", "100755"):
        return "file"
    return "symlink" if mode == "120000" else "other"


def tree_paths(rev):
    """Map every path under records/ at rev to (mode, object id)."""
    paths = {}
    output = git("ls-tree", "-r", "-z", "--full-tree", rev, "--", RECORDS)
    for item in output.split(b"\0"):
        if item:
            meta, path = item.split(b"\t", 1)
            mode, _, oid = meta.decode().split()
            paths[os.fsdecode(path)] = (mode, oid)
    return paths


def diff_paths(args):
    """Map each path git diff-tree reports under records/ to (status, mode, object id)."""
    output = git("diff-tree", "-r", "-z", "--raw", "--no-renames", "--no-commit-id",
                 *args, "--", RECORDS)
    fields = output.split(b"\0")
    changes = {}
    for meta, path in zip(fields[::2], fields[1::2]):
        _, mode, _, oid, status = meta.decode().split()
        changes[os.fsdecode(path)] = (status, mode, oid)
    return changes


def commit_changes(commit):
    """Return what this commit itself changed under records/.

    A merge counts only the paths that differ from every parent; the rest belong
    to commits on the merged sides.
    """
    parents = git("rev-list", "--parents", "-n", "1", commit).decode().split()[1:]
    if not parents:
        return diff_paths(["--root", commit])
    changes = diff_paths([parents[0], commit])
    for parent in parents[1:]:
        other = diff_paths([parent, commit])
        changes = {path: value for path, value in changes.items() if path in other}
    return changes


def prefetch_blobs(commit):
    # In a blobless clone a numstat fetches this commit's blobs in one batch; cat-file
    # would otherwise fetch them one process at a time.
    git("diff-tree", "-r", "--root", "--no-renames", "--no-commit-id", "--numstat",
        commit, "--", RECORDS)


def has_amend_trailer(commit):
    value = git("log", "-1", f"--format=%(trailers:key={AMEND_KEY},valueonly,unfold)", commit)
    return any(line.strip() for line in value.decode(errors="replace").splitlines())


def blob_sizes(oids):
    oids = sorted(set(oids))
    if not oids:
        return {}
    output = git("cat-file", "--batch-check=%(objectname) %(objecttype) %(objectsize)",
                 stdin="\n".join(oids).encode() + b"\n")
    sizes = {}
    for line in output.decode().splitlines():
        fields = line.split()
        if len(fields) == 3 and fields[1] == "blob":
            sizes[fields[0]] = int(fields[2])
    return sizes


def top_level(path):
    return path[len(RECORDS):].split("/", 1)[0]


def check_push(base, head, import_commit):
    """Return (problems, commit count, new record count) for base..head."""
    head = commit_id(head)
    base = None if not base or re.fullmatch("0+", base) else commit_id(base)
    imported_tree = tree_paths(commit_id(import_commit, "; CI needs fetch-depth: 0"))
    imported = {top_level(path) for path in imported_tree if path != INDEX}
    base_tree = tree_paths(base) if base else {}
    head_tree = tree_paths(head)
    range_args = [head] if base is None else [head, f"^{base}"]
    commits = git("rev-list", "--reverse", "--topo-order", *range_args).decode().split()

    problems = set()
    written = set()  # (path, mode, oid) written by any commit, even if removed later
    for commit in commits:
        changes = commit_changes(commit)
        changes.pop(INDEX, None)
        amended = None
        for path, (status, mode, oid) in changes.items():
            if path in base_tree:
                if amended is None:
                    amended = has_amend_trailer(commit)
                if not amended:
                    problems.add(f"{commit[:12]}: {path}: changes an existing record file "
                                 f"without an {AMEND_KEY}: <reason> trailer")
            if status != "D":
                written.add((path, mode, oid))
        if any(status != "D" for status, _, _ in changes.values()):
            prefetch_blobs(commit)

    sizes = blob_sizes(oid for _, mode, oid in written if entry_kind(mode) == "file")
    for path, mode, oid in written:
        kind = entry_kind(mode)
        size = sizes.get(oid) if kind == "file" else None
        problems.update(entry_problems(RECORDS.rstrip("/"), Entry(path[len(RECORDS):], kind, size)))

    new_tops = {top_level(path) for path in head_tree if path != INDEX}
    new_tops -= {top_level(path) for path in base_tree if path != INDEX}
    new_tops -= imported
    for top in sorted(new_tops):
        label = f"{RECORDS}{top}"
        problems.update(name_problems(label, top))
        entries = [
            Entry(path[len(label) + 1:], entry_kind(mode), None)
            for path, (mode, _) in head_tree.items()
            if path.startswith(f"{label}/")
        ]
        if entries:
            problems.update(readme_problems(
                label, entries,
                lambda: decode_text(git("cat-file", "blob", f"{head}:{label}/README.md")),
            ))
        else:
            problems.add(f"{label}: a new record must be a directory with a README.md")
    return sorted(problems), len(commits), len(new_tops)


def report(problems):
    for problem in problems:
        print(problem.replace("\r", "\\r").replace("\n", "\\n"), file=sys.stderr)
    return 1 if problems else 0


def main():
    sys.stderr.reconfigure(errors="backslashreplace")
    sys.stdout.reconfigure(errors="backslashreplace")
    parser = argparse.ArgumentParser(description="Validate evidence records.")
    commands = parser.add_subparsers(dest="command", required=True)
    record = commands.add_parser("record", help="validate a candidate record directory")
    record.add_argument("directory")
    record.add_argument("--name", help="record name; defaults to the directory's basename")
    push = commands.add_parser("push", help="validate a commit range in this repository")
    push.add_argument("--base", default="",
                      help="range base; empty or all zeros means everything in head")
    push.add_argument("--head", required=True, help="range head")
    push.add_argument("--import-commit", default=IMPORT_COMMIT,
                      help="commit whose records predate the name and README rules")
    args = parser.parse_args()

    if args.command == "record":
        return report(check_record(args.directory, args.name))
    try:
        problems, commits, records = check_push(args.base, args.head, args.import_commit)
    except GitError as error:
        print(f"check.py: {error}", file=sys.stderr)
        return 2
    if not problems:
        print(f"ok: {commits} commit(s), {records} new record(s)")
    return report(problems)


if __name__ == "__main__":
    sys.exit(main())
